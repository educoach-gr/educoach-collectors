import unittest

from . import browser, diavgeia, fek

MINISTER = 'Η ΥΠΟΥΡΓΟΣ ΠΑΙΔΕΙΑΣ, ΘΡΗΣΚΕΥΜΑΤΩΝ ΚΑΙ ΑΘΛΗΤΙΣΜΟΥ'
RECTOR = 'Ο ΠΡΥΤΑΝΗΣ ΤΟΥ ΠΑΝΕΠΙΣΤΗΜΙΟΥ ΑΙΓΑΙΟΥ'


class Fek(unittest.TestCase):
    def keep(self, title, head='', cat=None):
        got, why = fek.classify(title, head)
        self.assertTrue(got, f'dropped ({why}): {title}')
        if cat:
            self.assertEqual(got, cat)

    def drop(self, title, head=''):
        got, why = fek.classify(title, head)
        self.assertIsNone(got, f'kept as {got} ({why}): {title}')

    def test_kept(self):
        self.keep('Τροποποίηση της υπό στοιχεία Φ.251/119188/Α5/2022 υπουργικής απόφασης «Τρόπος εξέτασης των πανελλαδικά '
                  'εξεταζόμενων μαθημάτων για εισαγωγή στην Τριτοβάθμια Εκπαίδευση υποψηφίων Γενικού Λυκείου»', cat='admission')
        self.keep('Καθορισμός αριθμού εισακτέων στα Α.Ε.Ι. για το ακαδημαϊκό έτος 2027-2028', MINISTER, 'admission')
        self.keep('Ένταξη εκατόν είκοσι πέντε (125) δημοτικών σχολείων στο πρόγραμμα «Σχολικά Γεύματα» για το σχολικό έτος 2026-2027.')
        self.keep('Χορήγηση υποτροφιών σε φοιτητές του Πανεπιστημίου Κρήτης από το κληροδότημα', RECTOR, 'opportunities')
        self.keep('Διδακτέα - εξεταζόμενη ύλη του μαθήματος Επιλογής «Ναυτιλιακές Γνώσεις» της Α’ τάξης ΕΠΑ.Λ.', MINISTER)

    def test_dropped(self):
        self.drop('Καθιέρωση υπερωριακής εργασίας υπαλλήλων του Χαροκοπείου Πανεπιστημίου για το Β’ εξάμηνο 2026')
        self.drop('Τροποποίηση της απόφασης επανίδρυσης του Προγράμματος Μεταπτυχιακών Σπουδών με τίτλο: «Χρηματοοικονομική Διοίκηση»', RECTOR)
        self.drop('Συγκρότηση επιτροπής παρακολούθησης και συντονισμού της ύλης των πανελλαδικώς εξεταζόμενων μαθημάτων', MINISTER)
        self.drop('Μετονομασία 14ου Γενικού Λυκείου Θεσσαλονίκης', MINISTER)
        self.drop('Τροποποίηση της άδειας του Κέντρου Διά Βίου Μάθησης (Κ.Δ.Β.Μ.) του νομικού προσώπου με την επωνυμία «…»')
        self.drop('Ίδρυση Τμήματος Δοκίμων Αστυφυλάκων Αμφίκλειας.', MINISTER)
        self.drop('Πολιτογράφηση ομογενών αλλοδαπών')

    def test_split_acts(self):
        body = ('ΠΕΡΙΕΧΟΜΕΝΑ\nΑΠΟΦΑΣΕΙΣ\n1 Πολιτογράφηση αλλοδαπών. 76479\n2 Απόκτηση της ελληνικής ιθαγένειας. 76481\n'
                'ΑΠΟΦΑΣΕΙΣ\n(1)\nΠολιτογράφηση αλλοδαπών.\n1. Με την υπό στοιχεία Φ.31811/2026 απόφαση')
        self.assertEqual(fek.split_acts(body), ['Πολιτογράφηση αλλοδαπών', 'Απόκτηση της ελληνικής ιθαγένειας'])
        one = 'ΑΠΟΦΑΣΕΙΣ\nΑριθμ. 48051\nΚαθορισμός αριθμού εισακτέων στα Α.Ε.Ι.\n' + MINISTER + '\nΈχοντας υπόψη:\n1. Τις διατάξεις'
        self.assertEqual(fek.split_acts(one), ['Καθορισμός αριθμού εισακτέων στα Α.Ε.Ι.'])


class Diavgeia(unittest.TestCase):
    M = diavgeia.MINISTRY

    def test_kept(self):
        for title, typ in [
            ('Εγκύκλιος έναρξης της Ενισχυτικής Διδασκαλίας Γυμνασίου για το σχολικό έτος 2026-2027', 'Α.3'),
            ('«Ηλεκτρονική παρακολούθηση και συντονισμός της ύλης των πανελλαδικώς εξεταζόμενων μαθημάτων της Γ΄ τάξης ΕΠΑ.Λ.»', 'Α.3'),
            ('Μεταβολές σχολικών μονάδων Δευτεροβάθμιας Επαγγελματικής Εκπαίδευσης για το σχολικό έτος 2027-2028', 'Α.3'),
            ('Τροποποίηση της υπουργικής απόφασης «Τρόπος εξέτασης των πανελλαδικά εξεταζόμενων μαθημάτων για εισαγωγή στην Τριτοβάθμια Εκπαίδευση»', 'Α.2'),
        ]:
            self.assertTrue(diavgeia.classify(title, typ, self.M)[0], title)

    def test_dropped(self):
        for title, typ in [
            ('Πρόσληψη 592 εκπαιδευτικών Δευτεροβάθμιας Εκπαίδευσης, στη Γενική Εκπαίδευση, ως προσωρινών αναπληρωτών', '2.4.7.1'),
            ('Προκήρυξη Πανελλήνιων Αγώνων Ποδοσφαίρου Α΄ Φάσης ΓΕ.Λ. – ΕΠΑ.Λ. Ελλάδας - Κύπρου σχ. Έτους 2026-2027', '2.4.7.1'),
            ('Συγκρότηση επιτροπής παρακολούθησης και συντονισμού της ύλης των μαθημάτων της Γ’ τάξης ΓΕΛ που εξετάζονται πανελλαδικά.', '2.4.7.1'),
            ('Έγκριση ανάθεσης υπερωριακής απασχόλησης στο κανονικό ωρολόγιο πρόγραμμα', '2.4.7.1'),
            ('Απόφαση ορισμού Προϊσταμένης 14ου Νηπ. Θεσσαλονίκης', 'Α.2'),
            ('ΕΝΤΟΛΗ ΜΕΤΑΚΙΝΗΣΗΣ', '2.4.7.1'),
        ]:
            self.assertIsNone(diavgeia.classify(title, typ, self.M)[0], title)


class Dates(unittest.TestCase):
    def test_find_date(self):
        self.assertEqual(browser.find_date('Δελτία Τύπου Νοε 10, 2026'), '2026-11-10')
        self.assertEqual(browser.find_date('12 Νοεμβρίου 2026 · Ανακοινώσεις'), '2026-11-12')
        self.assertEqual(browser.find_date('Published 3 March 2026'), '2026-03-03')
        self.assertEqual(browser.find_date('17/11/2026'), '2026-11-17')
        self.assertEqual(browser.find_date('', '2026-11-05T10:00:00+02:00'), '2026-11-05')
        self.assertEqual(browser.find_date('no date here 12345'), '')


if __name__ == '__main__':
    unittest.main()
